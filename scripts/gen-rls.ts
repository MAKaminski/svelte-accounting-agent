// Generates drizzle/0001_rls.sql from TENANT_TABLES: the runtime role, grants, and one isolation policy per table.
// The owner (migrations, auth lookups) bypasses RLS; books_app (set per request via SET ROLE) never does.
import { writeFileSync, readFileSync } from 'node:fs';
import { TENANT_TABLES } from '../src/lib/server/db/schema';

const parts = [
  `DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'books_app') THEN CREATE ROLE books_app NOLOGIN; END IF; END $$;`,
  // The app connects as the owner and drops to books_app per org context (SET ROLE), so the owner must be a member.
  `DO $$ BEGIN IF NOT pg_has_role(current_user, 'books_app', 'MEMBER') THEN EXECUTE format('GRANT books_app TO %I', current_user); END IF; END $$;`,
  `GRANT USAGE ON SCHEMA public TO books_app;`,
  `GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO books_app;`,
  `ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO books_app;`,
  ...TENANT_TABLES.flatMap((t) => [
    `ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`,
    `CREATE POLICY "tenant_isolation" ON "${t}" USING ("org_id" = current_setting('app.org_id', true)) WITH CHECK ("org_id" = current_setting('app.org_id', true));`
  ])
];
const sql = '-- Generated by scripts/gen-rls.ts — do not edit by hand.\n' + parts.join('\n--> statement-breakpoint\n') + '\n';
const path = 'drizzle/0001_rls.sql';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) { console.error('✗ drizzle/0001_rls.sql is stale — run pnpm tsx scripts/gen-rls.ts'); process.exit(1); }
  console.error(`✓ RLS migration covers ${TENANT_TABLES.length} tenant tables`);
} else {
  writeFileSync(path, sql);
  console.error(`wrote ${path} (${TENANT_TABLES.length} tables)`);
}
